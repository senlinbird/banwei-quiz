const MAX_B = 44;      // 班味总分满分

// 班味浓度映射（分段线性，按全组合分布校准档位比例：清淡~32% / 中度~17% / 深度~32% / 陈年~19%）
// 锚点: B=0→3%, B=26→39%, B=32→79%, B=44→99%
function concentration(B) {
  let f;
  if (B <= 26) f = Math.round(3 + (B / 26) * 36);
  else if (B <= 32) f = Math.round(40 + ((B - 26) / 6) * 39);
  else f = Math.round(80 + ((B - 32) / 12) * 19);
  return Math.min(99, Math.max(3, f));
}

// 计分：answers = [选项下标(0-based) x12]
function score(answers) {
  let W = 0, E = 0, S = 0, R = 0;
  answers.forEach((optIdx, qi) => {
    const o = QUESTIONS[qi].options[optIdx];
    if (!o) throw new Error('bad answer');
    W += o.w; E += o.e; S += o.s; R += o.r;
  });
  const B = W + E + S;
  const final = concentration(B);
  return { W, E, S, R, B, final };
}

